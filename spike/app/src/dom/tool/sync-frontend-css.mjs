// THROWAWAY SPIKE. Regenerates src/dom/tool/frontend-index.css from the web frontend's src/index.css, minus its two package @imports, which cannot resolve from frontend/src because the frontend has no node_modules.
//
// Run: node src/dom/tool/sync-frontend-css.mjs   (from the app folder)
// Everything else in the stylesheet is copied byte for byte. tool.css imports
// 'tailwindcss' itself (resolved from this app's node_modules) and does without
// 'tw-animate-css' (not installed here), so Radix open/close animations are absent.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../../../../../../openalgo/frontend/src/index.css');
const out = path.join(here, 'frontend-index.css');

const css = fs.readFileSync(src, 'utf8');
const dropped = [];
const body = css
  .split('\n')
  .filter((line) => {
    const m = /^@import\s+["'](tailwindcss|tw-animate-css)["'];\s*$/.exec(line.trim());
    if (m) dropped.push(m[1]);
    return !m;
  })
  .join('\n');

if (dropped.length !== 2) {
  throw new Error(`expected to drop 2 @imports from ${src}, dropped: ${dropped.join(', ') || 'none'}`);
}

const header =
  '/* THROWAWAY SPIKE. GENERATED by sync-frontend-css.mjs from openalgo/frontend/src/index.css; do not edit.\n' +
  `   Dropped: @import "${dropped.join('", @import "')}" (unresolvable from frontend/src, see CHANGES.tool.md). */\n`;
fs.writeFileSync(out, header + body);
console.log(`wrote ${out} (${(header + body).length} bytes)`);
