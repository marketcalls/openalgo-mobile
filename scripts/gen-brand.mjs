// Brand assets (assets/brand/README.md): derives the white mark and logo SVGs from the committed
// OpenAlgo logo and renders every PNG the app ships. The renderer is not an app dependency; it is
// installed into a throwaway folder whose path is the one argument:
//
//   npm install --prefix <tools> --no-save @resvg/resvg-js@2.6.2 pngjs@7.0.0
//   node scripts/gen-brand.mjs <tools>
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = 'assets/brand/openalgo-logo.svg'
const WHITE = '#FFFFFF'
const BLACK = '#000000'
/** In the source the mark ends above this line and the OPENALGO wordmark starts below it. */
const WORDMARK_TOP = 625
/** Android's adaptive-icon safe zone: a 66 dp circle on the 108 dp canvas. */
const ADAPTIVE_SAFE_RADIUS = 33 / 108
/**
 * Android 12+ draws the splash image centred in a 288 dp icon and masks it to a 192 dp circle;
 * expo-splash-screen sizes the image to `imageWidth` (200 dp in app.config.ts), so everything must
 * lie within 96 dp of the centre, 0.48 of the image width.
 */
const SPLASH_SAFE_RADIUS = 96 / 200

/**
 * Every PNG: its canvas (square, px), the art (`mark`, or `logo` = mark and wordmark), the art's
 * larger side as a fraction of the canvas, the background (none means transparent) and, for the
 * masked ones, the radius (fraction of the canvas) every drawn pixel must stay inside.
 */
export const OUTPUTS = [
  { file: 'assets/images/icon.png', size: 1024, art: 'mark', scale: 0.62, background: BLACK },
  {
    file: 'assets/images/android-icon-foreground.png',
    size: 1024,
    art: 'mark',
    scale: 0.52,
    safeRadius: ADAPTIVE_SAFE_RADIUS,
  },
  {
    file: 'assets/images/android-icon-monochrome.png',
    size: 1024,
    art: 'mark',
    scale: 0.52,
    safeRadius: ADAPTIVE_SAFE_RADIUS,
  },
  {
    file: 'assets/images/splash-icon.png',
    size: 1024,
    art: 'logo',
    scale: 0.68,
    safeRadius: SPLASH_SAFE_RADIUS,
  },
  { file: 'assets/images/favicon.png', size: 48, art: 'mark', scale: 0.8, background: BLACK },
  { file: 'assets/brand/openalgo-mark.png', size: 64, art: 'mark', scale: 1 },
  { file: 'assets/brand/openalgo-mark@2x.png', size: 128, art: 'mark', scale: 1 },
  { file: 'assets/brand/openalgo-mark@3x.png', size: 192, art: 'mark', scale: 1 },
]

/** The source's light (near-white) paths' `d` strings; the dark ones are its background. */
export function lightPaths(svg) {
  const out = []
  for (const [tag] of svg.matchAll(/<path\b[^>]*\/>/g)) {
    const fill = tag.match(/\bfill="#([0-9a-f]{6})"/i)?.[1]
    const d = tag.match(/\bd="([^"]+)"/)?.[1]?.trim()
    if (!fill || !d) throw new Error(`unexpected path in ${SOURCE}: ${tag.slice(0, 60)}`)
    const channels = [0, 2, 4].map((i) => Number.parseInt(fill.slice(i, i + 2), 16))
    if (channels.every((v) => v >= 0xe0)) out.push(d)
  }
  return out
}

const num = (v) => String(Number(v.toFixed(3)))
const pathsSvg = (ds) => ds.map((d) => `<path fill="${WHITE}" d="${d}"/>`).join('')

/** The tight box around `ds`, rounded outward to 0.1 unit. */
function box(Resvg, ds) {
  const b = new Resvg(
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">${pathsSvg(ds)}</svg>`,
  ).getBBox()
  if (!b) throw new Error('nothing to measure')
  const x = Math.floor(b.x * 10) / 10
  const y = Math.floor(b.y * 10) / 10
  const w = Math.ceil((b.x + b.width) * 10) / 10 - x
  const h = Math.ceil((b.y + b.height) * 10) / 10 - y
  return { x, y, w: Number(w.toFixed(1)), h: Number(h.toFixed(1)) }
}

function standaloneSvg(ds, b, what) {
  return [
    '<svg xmlns="http://www.w3.org/2000/svg"',
    ` viewBox="${b.x} ${b.y} ${b.w} ${b.h}">`,
    `<!-- ${what}: the light paths of ${SOURCE} (from openalgo-charts/assets/openalgo-logo.svg),`,
    ` recoloured ${WHITE}, without the background, cropped to the drawing.`,
    ' Generated by scripts/gen-brand.mjs. -->\n',
    '<title>OpenAlgo</title>\n',
    pathsSvg(ds),
    '</svg>\n',
  ].join('')
}

function canvasSvg(ds, b, { size, scale, background }) {
  const k = (size * scale) / Math.max(b.w, b.h)
  const tx = size / 2 - (b.x + b.w / 2) * k
  const ty = size / 2 - (b.y + b.h / 2) * k
  const bg = background ? `<rect width="${size}" height="${size}" fill="${background}"/>` : ''
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"`,
    ` viewBox="0 0 ${size} ${size}">${bg}`,
    `<g transform="translate(${num(tx)} ${num(ty)}) scale(${num(k)})">${pathsSvg(ds)}</g></svg>`,
  ].join('')
}

/** What is drawn: the box of the pixels with any alpha and the farthest one from the centre. */
function measure(png, opaque) {
  const { width, height, data } = png
  let [minX, minY, maxX, maxY, far] = [width, height, -1, -1, 0]
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4
      const ink = opaque ? data[i] > 0 : data[i + 3] > 0
      if (!ink) continue
      minX = Math.min(minX, x)
      minY = Math.min(minY, y)
      maxX = Math.max(maxX, x)
      maxY = Math.max(maxY, y)
      // The pixel's far corner, so a partly covered edge pixel counts in full.
      const dx = Math.max(Math.abs(x - width / 2), Math.abs(x + 1 - width / 2))
      const dy = Math.max(Math.abs(y - height / 2), Math.abs(y + 1 - height / 2))
      far = Math.max(far, Math.hypot(dx, dy))
    }
  }
  return {
    drawn: maxX >= 0,
    left: minX,
    top: minY,
    right: width - 1 - maxX,
    bottom: height - 1 - maxY,
    far,
  }
}

function main(argv) {
  const tools = argv[0]
  if (!tools) {
    console.error('usage: gen-brand.mjs <folder where @resvg/resvg-js and pngjs are installed>')
    return 2
  }
  const req = createRequire(join(resolve(tools), 'package.json'))
  const { Resvg } = req('@resvg/resvg-js')
  const { PNG } = req('pngjs')

  const source = readFileSync(join(root, SOURCE), 'utf8')
  const light = lightPaths(source)
  const mark = []
  const wordmark = []
  for (const d of light) (box(Resvg, [d]).y < WORDMARK_TOP ? mark : wordmark).push(d)
  if (mark.length !== 1 || wordmark.length !== 8) {
    throw new Error(`expected 1 mark path and 8 letters, got ${mark.length} and ${wordmark.length}`)
  }
  const art = { mark, logo: [...mark, ...wordmark] }
  const boxes = { mark: box(Resvg, art.mark), logo: box(Resvg, art.logo) }

  writeFileSync(
    join(root, 'assets/brand/openalgo-mark.svg'),
    standaloneSvg(art.mark, boxes.mark, 'The OpenAlgo mark'),
  )
  writeFileSync(
    join(root, 'assets/brand/openalgo-logo-white.svg'),
    standaloneSvg(art.logo, boxes.logo, 'The OpenAlgo logo (mark and wordmark), white'),
  )
  console.log(`mark box ${JSON.stringify(boxes.mark)}, logo box ${JSON.stringify(boxes.logo)}`)

  for (const out of OUTPUTS) {
    const svg = canvasSvg(art[out.art], boxes[out.art], out)
    const png = PNG.sync.read(new Resvg(svg, { fitTo: { mode: 'original' } }).render().asPng())
    if (png.width !== out.size || png.height !== out.size) throw new Error(`${out.file}: size`)
    const opaque = Boolean(out.background)
    for (let i = 0; i < png.data.length; i += 4) {
      if (opaque) {
        if (png.data[i + 3] !== 255) throw new Error(`${out.file}: a transparent pixel`)
      } else {
        // White art: the shape lives in the alpha channel. Writing every pixel's colour as pure
        // white leaves no dark fringe when the image is scaled or tinted.
        png.data[i] = 255
        png.data[i + 1] = 255
        png.data[i + 2] = 255
      }
    }
    const m = measure(png, opaque)
    if (!m.drawn) throw new Error(`${out.file}: nothing drawn`)
    // Art smaller than its canvas must not reach an edge: touching one means it was cut off.
    if (out.scale < 1 && Math.min(m.left, m.top, m.right, m.bottom) < 1) {
      throw new Error(`${out.file}: clipped at the edge of the canvas`)
    }
    if (out.safeRadius && m.far > out.safeRadius * out.size) {
      throw new Error(
        `${out.file}: drawn ${m.far.toFixed(1)} px from the centre, outside the safe zone`,
      )
    }
    const bytes = PNG.sync.write(png, {
      colorType: opaque ? 2 : 6,
      inputHasAlpha: true,
      deflateLevel: 9,
    })
    writeFileSync(join(root, out.file), bytes)
    const reach = (m.far / out.size).toFixed(3)
    console.log(
      `${out.file}: ${out.size}px ${opaque ? 'RGB' : 'RGBA'} ${bytes.length} B, margins ` +
        `${m.left}/${m.top}/${m.right}/${m.bottom} px, farthest ${reach} of the canvas from the centre`,
    )
  }
  return 0
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exit(main(process.argv.slice(2)))
}
